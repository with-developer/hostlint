package rulesdoc

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"strings"

	"github.com/with-developer/hostlint/internal/engine"
)

// RenderFacts writes the reference of the facts a check can read: every path of every collector, with its
// type and the documentation comment of its Go declaration, read from the Go files in srcDirs.
func RenderFacts(e *engine.Engine, src fs.FS, srcDirs ...string) (string, error) {
	docs, err := fieldDocs(src, srcDirs)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("<!-- Generated by `make docs` from the fact types of the collectors. Do not edit. -->\n")
	b.WriteString("# Fact reference\n\n")
	b.WriteString("What a check or a [policy pack](packs.md) can read: the facts the compiled-in collectors produce. A rule\n")
	b.WriteString("names a fact by its path, for example `sshd.config.permitrootlogin.value`. `[]` stands for an element of a\n")
	b.WriteString("list (`sshd.match[].criteria`, written with `over:` and an element variable in a `violations` check), `{}` for the\n")
	b.WriteString("value under any key of a map (`sshd.config{}.value`, written `sshd.config.permitrootlogin.value` or\n")
	b.WriteString("`sshd.config[\"permitrootlogin\"].value` in a rule). A `setting` is a configuration value with `value`, `explicit`\n")
	b.WriteString("and `source`; one that is not set and has no known default is absent from its map, so a rule that reads it\n")
	b.WriteString("fails with `ERROR` instead of guessing. `hostlint pack facts` prints the same names.\n\n")
	b.WriteString("The fact types are the contract of rule authors, but before v1.0 they can change in a minor release.\n")
	for _, f := range e.FactCatalog() {
		root, _, nested := strings.Cut(f.Path, ".")
		if !nested {
			b.WriteString("\n## `" + root + "`\n\n")
			if d := docs[f.Go]; d != "" {
				b.WriteString(d + "\n\n")
			}
			b.WriteString("| Path | Type | |\n|---|---|---|\n")
			continue
		}
		b.WriteString("| `" + f.Path + "` | " + f.Type + " | " + strings.ReplaceAll(oneLine(docs[f.Go]), "|", `\|`) + " |\n")
	}
	return b.String(), nil
}

// fieldDocs reads the doc comments of types ("Type") and struct fields ("Type.Field") of the Go files in
// the directories, without their tests.
func fieldDocs(src fs.FS, dirs []string) (map[string]string, error) {
	out := map[string]string{}
	fset := token.NewFileSet()
	for _, dir := range dirs {
		names, err := fs.Glob(src, dir+"/*.go")
		if err != nil {
			return nil, err
		}
		for _, name := range names {
			if strings.HasSuffix(name, "_test.go") {
				continue
			}
			data, err := fs.ReadFile(src, name)
			if err != nil {
				return nil, err
			}
			file, err := parser.ParseFile(fset, name, data, parser.ParseComments)
			if err != nil {
				return nil, err
			}
			for _, decl := range file.Decls {
				gd, ok := decl.(*ast.GenDecl)
				if !ok || gd.Tok != token.TYPE {
					continue
				}
				for _, spec := range gd.Specs {
					ts := spec.(*ast.TypeSpec)
					doc := ts.Doc
					if doc == nil && len(gd.Specs) == 1 {
						doc = gd.Doc // the comment of a group belongs to no single type of it
					}
					if doc != nil {
						if err := put(out, ts.Name.Name, doc.Text()); err != nil {
							return nil, err
						}
					}
					st, ok := ts.Type.(*ast.StructType)
					if !ok {
						continue
					}
					for _, f := range st.Fields.List {
						text := ""
						if f.Doc != nil {
							text = f.Doc.Text()
						} else if f.Comment != nil {
							text = f.Comment.Text()
						}
						for _, n := range f.Names {
							if text != "" {
								if err := put(out, ts.Name.Name+"."+n.Name, text); err != nil {
									return nil, err
								}
							}
						}
					}
				}
			}
		}
	}
	return out, nil
}

// put records a comment; the same name twice (two types of that name in the directories read) is an error,
// not a comment that silently wins.
func put(out map[string]string, key, text string) error {
	if _, dup := out[key]; dup {
		return fmt.Errorf("%s is declared twice: the documentation of the facts is keyed by type and field name", key)
	}
	out[key] = strings.TrimSpace(text)
	return nil
}
