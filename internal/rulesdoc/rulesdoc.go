// Package rulesdoc renders the rule reference (docs/rules.md) from the
// built-in profiles and checks, so that the page cannot drift from them.
package rulesdoc

import (
	"fmt"
	"slices"
	"strings"

	"github.com/with-developer/hostlint/internal/engine"
)

// Render returns the reference for every profile of content, in profile ID
// order. The text is deterministic.
func Render(content *engine.Content) string {
	var b strings.Builder
	b.WriteString("<!-- Generated by `make docs` from rules/ and profiles/. Do not edit. -->\n")
	b.WriteString("# Rule reference\n\n")
	b.WriteString("Every control of a profile and the checks that decide it. A control passes only when every\n")
	b.WriteString("check applicable to it passes; checks that cannot decide report `MANUAL` or `ERROR`, never\n")
	b.WriteString("`PASS` (see [ADR 0006](adr/0006-rule-format-evaluation-results.md)). Control IDs come from the\n")
	b.WriteString("standard; titles and descriptions are hostlint's own. Parameters can be made stricter in\n")
	b.WriteString("[hostlint.yaml](configuration.md).\n")

	ids := make([]string, 0, len(content.Profiles))
	for id := range content.Profiles {
		ids = append(ids, id)
	}
	slices.Sort(ids)
	for _, id := range ids {
		renderProfile(&b, content, content.Profiles[id])
	}
	return b.String()
}

func renderProfile(b *strings.Builder, content *engine.Content, p *engine.Profile) {
	fmt.Fprintf(b, "\n## %s (revision %d)\n\n%s\n\n", p.ID, p.Revision, oneLine(p.Title))
	b.WriteString("| Control | Severity | Title | Checks |\n|---|---|---|---|\n")
	for _, c := range p.Controls {
		checks := make([]string, 0, len(c.Checks))
		for _, ref := range c.Checks {
			checks = append(checks, fmt.Sprintf("[`%s`](#%s)", ref, anchor(ref)))
		}
		if len(checks) == 0 {
			checks = append(checks, "review by hand")
		}
		fmt.Fprintf(b, "| %s | %s | %s (%s) | %s |\n", c.ID, c.Severity, oneLine(c.Title), oneLine(c.TitleKo), strings.Join(checks, ", "))
	}

	seen := map[string]bool{}
	var order []string
	for _, c := range p.Controls {
		for _, ref := range c.Checks {
			if !seen[ref] {
				seen[ref] = true
				order = append(order, ref)
			}
		}
	}
	slices.Sort(order)
	b.WriteString("\n### Checks\n")
	for _, ref := range order {
		ck := content.Checks[ref]
		if ck == nil {
			continue
		}
		fmt.Fprintf(b, "\n#### `%s`\n\n%s (%s) — severity %s, %s.\n\n", ck.ID, oneLine(ck.Title), oneLine(ck.TitleKo), ck.Severity, kind(ck))
		fmt.Fprintf(b, "%s\n", oneLine(ck.Description))
		if ck.Rationale != "" {
			fmt.Fprintf(b, "\n**Why.** %s\n", oneLine(ck.Rationale))
		}
		if ck.Remediation != "" {
			fmt.Fprintf(b, "\n**Fix.** %s\n", oneLine(ck.Remediation))
		}
		if len(ck.Params) > 0 {
			names := make([]string, 0, len(ck.Params))
			for n := range ck.Params {
				names = append(names, n)
			}
			slices.Sort(names)
			b.WriteString("\n**Parameters.**\n\n")
			for _, n := range names {
				ps := ck.Params[n]
				dir := ""
				if ps.Stricter != "" {
					dir = fmt.Sprintf(", %s is stricter", ps.Stricter)
				}
				fmt.Fprintf(b, "- `%s` (%s, default `%v`%s): %s\n", n, ps.Type, ps.Default, dir, oneLine(ps.Description))
			}
		}
	}
}

// kind says how a check decides.
func kind(c *engine.Check) string {
	switch {
	case c.Manual != nil:
		return "a review (`MANUAL`)"
	case c.Violations != nil:
		return "lists what violates it"
	case c.File != nil:
		return "reads file metadata"
	case c.Setting != nil:
		return "compares one setting"
	}
	return "evaluates an expression"
}

// anchor is the GitHub anchor of a "#### `id`" heading.
func anchor(id string) string {
	return strings.NewReplacer(".", "", "-", "-").Replace(id)
}

// oneLine joins a YAML text into one line.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }
