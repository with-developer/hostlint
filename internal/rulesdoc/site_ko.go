import (
	"fmt"
	"html"
	"strings"

	"github.com/with-developer/vmsctl/internal/engine"
)

// RenderKISASiteKo returns the Korean project page of the KISA profile (site/ko/kisa/index.html): every control with the
// checks behind it, in Korean, as a static page that a search engine can read. It is made from the same rules as the rule
// reference, so it cannot drift from them. The control IDs come from the guide; the titles and texts are vmsctl's own.
func RenderKISASiteKo(content *engine.Content, profileID string) (string, error) {
	p := content.Profiles[profileID]
	if p == nil {
		return "", fmt.Errorf("no profile %q", profileID)
	}
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	first, last := p.Controls[0].ID, p.Controls[len(p.Controls)-1].ID
	title := fmt.Sprintf("KISA 2026 Unix 서버 점검 항목 %s~%s: 점검 내용과 조치 방법 — vmsctl", first, last)
	desc := fmt.Sprintf("주요정보통신기반시설 기술적 취약점 분석·평가 상세가이드(2026) Unix 서버 점검 항목 %d개가 무엇을 보고, 왜 중요하고, 어떻게 고치는지 한국어로 정리했습니다. vmsctl이 각 항목을 자동으로 점검합니다.", len(p.Controls))
	const url = "https://with-developer.github.io/vmsctl/ko/kisa/"

	w("<!doctype html>\n<!-- Generated by `make docs` from rules/ and profiles/. Do not edit. -->\n")
	w("<html lang=\"ko\">\n<head>\n<meta charset=\"utf-8\">\n<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n")
	w("<title>%s</title>\n", html.EscapeString(title))
	w("<meta name=\"description\" content=\"%s\">\n", html.EscapeString(desc))
	w("<meta name=\"color-scheme\" content=\"light dark\">\n")
	w("<link rel=\"canonical\" href=\"%s\">\n", url)
	w("<meta property=\"og:type\" content=\"article\">\n<meta property=\"og:site_name\" content=\"vmsctl\">\n<meta property=\"og:locale\" content=\"ko_KR\">\n")
	w("<meta property=\"og:title\" content=\"%s\">\n<meta property=\"og:description\" content=\"%s\">\n<meta property=\"og:url\" content=\"%s\">\n", html.EscapeString(title), html.EscapeString(desc), url)
	w("<link rel=\"stylesheet\" href=\"../../style.css\">\n</head>\n<body>\n")
	w("<header class=\"top\">\n  <div class=\"wrap\">\n    <a class=\"brand\" href=\"../\">vmsctl</a>\n    <nav>\n      <a href=\"https://github.com/with-developer/vmsctl\">GitHub</a>\n      <a class=\"lang\" href=\"../\">홈</a>\n    </nav>\n  </div>\n</header>\n")
	w("<main>\n<article class=\"wrap doc\">\n")
	w("<h1>KISA 2026 Unix 서버 점검 항목 %s~%s</h1>\n", first, last)
	w("<p class=\"lead\">주요정보통신기반시설 기술적 취약점 분석·평가 상세가이드(2026)의 Unix 서버 점검 항목 %d개가 각각 무엇을 보고, 왜 중요하고, 어떻게 고치는지 정리했습니다. 점검 항목 번호는 가이드의 것이고, 제목과 설명은 vmsctl이 직접 쓴 것입니다. 아래 항목은 모두 <code>vmsctl</code>이 서버에서 읽기만 하며 자동으로 점검하고, 사람이 판단해야 하는 항목은 근거를 모아 보여 줍니다.</p>\n", len(p.Controls))
	w("<pre class=\"cmd\" tabindex=\"0\"><code>curl -fsSL https://raw.githubusercontent.com/with-developer/vmsctl/main/install.sh | sh\nsudo vmsctl scan --profile kisa-2026 --lang ko</code></pre>\n")
	w("<p class=\"muted\">결과마다 값과 파일, 줄 번호가 근거로 붙고, 조치 방법은 <code>vmsctl explain 점검ID --lang ko</code>로도 볼 수 있습니다. 설치와 사용법은 <a href=\"../\">vmsctl 소개</a>와 <a href=\"https://github.com/with-developer/vmsctl/blob/main/README.ko.md\">README</a>를 보세요.</p>\n")

	w("<nav class=\"toc\" aria-label=\"점검 항목 목록\">\n<ul>\n")
	for _, c := range p.Controls {
		w("<li><a href=\"#%s\"><b>%s</b> %s</a></li>\n", anchorID(c.ID), html.EscapeString(c.ID), html.EscapeString(ko(c.TitleKo, c.Title)))
	}
	w("</ul>\n</nav>\n")

	for _, c := range p.Controls {
		w("<section class=\"control\" id=\"%s\">\n<h2><span class=\"cid\">%s</span> %s</h2>\n", anchorID(c.ID), html.EscapeString(c.ID), html.EscapeString(ko(c.TitleKo, c.Title)))
		w("<p class=\"meta\">중요도 <b class=\"sev-%s\">%s</b></p>\n", html.EscapeString(string(c.Severity)), html.EscapeString(sev(c.Severity)))
		if len(c.Checks) == 0 {
			w("<p>이 항목은 자동 점검이 없고 사람이 직접 검토합니다.%s</p>\n", manualKo(c))
		}
		for _, ref := range c.Checks {
			ck := content.Checks[ref]
			if ck == nil {
				continue
			}
			w("<div class=\"check\">\n<h3><code>%s</code> %s</h3>\n", html.EscapeString(ck.ID), html.EscapeString(ko(ck.TitleKo, ck.Title)))
			w("<p>%s</p>\n", inline(ko(ck.DescriptionKo, ck.Description)))
			if ck.Rationale != "" || ck.RationaleKo != "" {
				w("<p><b>왜 중요한가.</b> %s</p>\n", inline(ko(ck.RationaleKo, ck.Rationale)))
			}
			if ck.Remediation != "" || ck.RemediationKo != "" {
				w("<p><b>조치 방법.</b> %s</p>\n", inline(ko(ck.RemediationKo, ck.Remediation)))
			}
			if ck.Manual != nil && (ck.Manual.Guidance != "" || ck.Manual.GuidanceKo != "") {
				w("<p><b>사람이 판단합니다.</b> %s</p>\n", inline(ko(ck.Manual.GuidanceKo, ck.Manual.Guidance)))
			}
			w("</div>\n")
		}
		w("</section>\n")
	}
	w("</article>\n</main>\n")
	w("<footer>\n  <div class=\"wrap\">\n    <span>Apache-2.0 라이선스 · <a href=\"https://github.com/with-developer/vmsctl\">github.com/with-developer/vmsctl</a></span>\n    <span><a href=\"https://github.com/with-developer/vmsctl/blob/main/docs/rules.ko.md\">전체 규칙 참조</a> · <a href=\"../\">vmsctl 소개</a></span>\n  </div>\n</footer>\n</body>\n</html>\n")
	return b.String(), nil
}

// anchorID is the fragment of a control: u-01.
func anchorID(id string) string { return strings.ToLower(strings.ReplaceAll(id, " ", "-")) }

// manualKo is the Korean text of a control that is reviewed by hand, when the profile has one.
func manualKo(c engine.Control) string {
	if t := ko(c.ManualKo, c.Manual); t != "" {
		return " " + html.EscapeString(t)
	}
	return ""
}

// inline escapes text and makes `code` spans of what is in backticks.
func inline(s string) string {
	parts := strings.Split(s, "`")
	var b strings.Builder
	for i, p := range parts {
		if i%2 == 1 && i < len(parts)-1 {
			b.WriteString("<code>" + html.EscapeString(p) + "</code>")
		} else if i%2 == 1 { // an unpaired backtick at the end: keep it as text
			b.WriteString("`" + html.EscapeString(p))
		} else {
			b.WriteString(html.EscapeString(p))
		}
	}
	return b.String()
}
