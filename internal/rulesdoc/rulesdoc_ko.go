// RenderKo returns the Korean rule reference (docs/rules.ko.md): the same controls and checks as Render, with the Korean
// title, description, reason and fix of each check where the rule has them and the English text where it has not. It is made
// from the same data, so it cannot drift from the rules either.
func RenderKo(content *engine.Content) string {
	var b strings.Builder
	b.WriteString("<!-- Generated by `make docs` from rules/ and profiles/. Do not edit. -->\n")
	b.WriteString("# 점검 항목 참조\n\n")
	b.WriteString("프로파일의 점검 항목마다 그것을 판정하는 점검을 모았습니다. 점검 항목은 적용되는 점검이 모두 통과할 때만 통과하고,\n")
	b.WriteString("판정할 수 없는 점검은 `MANUAL`이나 `ERROR`로 보고하며 `PASS`로 추측하지 않습니다\n")
	b.WriteString("([ADR 0006](adr/0006-rule-format-evaluation-results.md), 영어). 점검 항목 ID는 기준 문서에서 오고, 제목과 설명은 vmsctl이 직접 쓴 것입니다.\n")
	b.WriteString("매개변수는 [vmsctl.yaml](configuration.ko.md)에서 더 엄격하게 바꿀 수 있습니다. 영어판은 [rules.md](rules.md)입니다.\n")

	ids := make([]string, 0, len(content.Profiles))
	for id := range content.Profiles {
		ids = append(ids, id)
	}
	slices.Sort(ids)
	for _, id := range ids {
		renderProfileKo(&b, content, content.Profiles[id])
	}
	return b.String()
}

// ko is the Korean text when there is one, else the English.
func ko(korean, english string) string {
	if strings.TrimSpace(korean) != "" {
		return oneLine(korean)
	}
	return oneLine(english)
}

var severityKo = map[engine.Severity]string{"high": "높음", "medium": "중간", "low": "낮음"}

func sev(s engine.Severity) string {
	if v, ok := severityKo[s]; ok {
		return v
	}
	return string(s)
}

func renderProfileKo(b *strings.Builder, content *engine.Content, p *engine.Profile) {
	fmt.Fprintf(b, "\n## %s (리비전 %d)\n\n%s\n\n", p.ID, p.Revision, ko(p.TitleKo, p.Title))
	b.WriteString("| 점검 항목 | 심각도 | 제목 | 점검 |\n|---|---|---|---|\n")
	for _, c := range p.Controls {
		checks := make([]string, 0, len(c.Checks))
		for _, ref := range c.Checks {
			checks = append(checks, fmt.Sprintf("[`%s`](#%s)", ref, anchor(ref)))
		}
		if len(checks) == 0 {
			checks = append(checks, "직접 검토")
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s |\n", c.ID, sev(c.Severity), ko(c.TitleKo, c.Title), strings.Join(checks, ", "))
	}

	seen := map[string]bool{}
	var order []string
	for _, c := range p.Controls {
		for _, ref := range c.Checks {
			if !seen[ref] {
				seen[ref] = true
				order = append(order, ref)
			}
		}
	}
	slices.Sort(order)
	b.WriteString("\n### 점검\n")
	for _, ref := range order {
		ck := content.Checks[ref]
		if ck == nil {
			continue
		}
		fmt.Fprintf(b, "\n#### `%s`\n\n%s — 심각도 %s, %s.\n\n", ck.ID, ko(ck.TitleKo, ck.Title), sev(ck.Severity), kindKo(ck))
		fmt.Fprintf(b, "%s\n", ko(ck.DescriptionKo, ck.Description))
		if ck.Rationale != "" || ck.RationaleKo != "" {
			fmt.Fprintf(b, "\n**이유.** %s\n", ko(ck.RationaleKo, ck.Rationale))
		}
		if ck.Remediation != "" || ck.RemediationKo != "" {
			fmt.Fprintf(b, "\n**조치 방법.** %s\n", ko(ck.RemediationKo, ck.Remediation))
		}
		if len(ck.Params) > 0 {
			names := make([]string, 0, len(ck.Params))
			for n := range ck.Params {
				names = append(names, n)
			}
			slices.Sort(names)
			b.WriteString("\n**매개변수** (설명은 영어).\n\n")
			for _, n := range names {
				ps := ck.Params[n]
				dir := ""
				switch ps.Stricter {
				case "":
				case "lower":
					dir = ", 더 낮을수록 엄격"
				case "higher":
					dir = ", 더 높을수록 엄격"
				default:
					dir = fmt.Sprintf(", %s이(가) 더 엄격", ps.Stricter)
				}
				fmt.Fprintf(b, "- `%s` (%s, 기본값 `%v`%s): %s\n", n, ps.Type, ps.Default, dir, oneLine(ps.Description))
			}
		}
	}
}

// kindKo says how a check decides.
func kindKo(c *engine.Check) string {
	switch {
	case c.Manual != nil:
		return "사람이 검토합니다(`MANUAL`)"
	case c.Violations != nil:
		return "위반하는 것을 나열합니다"
	case c.File != nil:
		return "파일의 메타데이터를 읽습니다"
	case c.Setting != nil:
		return "설정 하나를 비교합니다"
	}
	return "식을 평가합니다"
}
